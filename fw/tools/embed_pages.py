"""把 Clawd-Mochi 设备自带的网页转成固件可用的 C 头文件。

输出 fw/src/web_pages.h：
    static const char PAGE_CONTROL[] PROGMEM = R"MOCHIHTML(...)MOCHIHTML";
    static const char PAGE_WIFI[]    PROGMEM = R"MOCHIHTML(...)MOCHIHTML";

来源二选一（推荐 --url：直接抓你自己的设备，无需解包安装包）：
  --url http://clawd-mochi.local   抓 GET /（设备控制器页）与 GET /wifi（配网页）
  --src DIR                        该目录下需有 embedded_19e9.html / embedded_5e0d.html
"""

import argparse
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
FW_DIR = os.path.dirname(HERE)
ROOT = os.path.dirname(FW_DIR)

OUT = os.path.join(FW_DIR, "src", "web_pages.h")
RAW = "MOCHIHTML"
UA = "clawd-mochi-toolkit/1.0"


def fetch(url, timeout=10):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read().decode("utf-8")


def load_file(path):
    if not os.path.exists(path):
        raise SystemExit("missing file: %s" % path)
    with open(path, "rb") as f:
        return f.read().decode("utf-8")


def check(text, label):
    if RAW in text:
        raise SystemExit("%s contains raw delimiter %s" % (label, RAW))
    return text


def main():
    ap = argparse.ArgumentParser(description="Embed Clawd-Mochi web pages into web_pages.h")
    ap.add_argument("--url", help="device base URL, e.g. http://clawd-mochi.local")
    ap.add_argument("--src", default=os.path.join(ROOT, "_work"),
                    help="directory with embedded_19e9.html / embedded_5e0d.html")
    ap.add_argument("--out", default=OUT, help="output header path")
    args = ap.parse_args()

    if args.url:
        base = args.url.rstrip("/")
        control = check(fetch(base + "/"), base + "/")
        wifi = check(fetch(base + "/wifi"), base + "/wifi")
        origin = base
    else:
        control = check(load_file(os.path.join(args.src, "embedded_19e9.html")), "embedded_19e9.html")
        wifi = check(load_file(os.path.join(args.src, "embedded_5e0d.html")), "embedded_5e0d.html")
        origin = args.src

    parts = [
        "// Auto-generated by fw/tools/embed_pages.py - do not edit.",
        "// Source: %s" % origin,
        "#pragma once",
        "#include <Arduino.h>",
        "",
        'static const char PAGE_CONTROL[] PROGMEM = R"%s(' % RAW,
        control,
        ')%s";' % RAW,
        "",
        'static const char PAGE_WIFI[] PROGMEM = R"%s(' % RAW,
        wifi,
        ')%s";' % RAW,
        "",
    ]
    body = "\n".join(parts)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("wrote %s (%d bytes); control %d chars, wifi %d chars" %
          (args.out, len(body), len(control), len(wifi)))


if __name__ == "__main__":
    main()
